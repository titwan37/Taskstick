// src/app/services/storage-migration.adapter.ts
import { Injectable } from '@angular/core';
import { TaskstickDbService } from './taskstick-db.service';
import { ADHDPostItNote, PostItColor, PostItStatus } from '../models/taskstick-graph.model';

@Injectable({ providedIn: 'root' })
export class StorageMigrationAdapter {
  constructor(private db: TaskstickDbService) {}

  /**
   * Scans localStorage for existing 'journal-YYYYMMDD' keys,
   * parses tasks into ADHDPostItNote records in IndexedDB without
   * modifying or deleting the original localStorage keys.
   */
  async migrateLegacyLocalStorage(): Promise<{ migratedDates: string[]; totalNotes: number }> {
    const migratedDates: string[] = [];
    let totalNotes = 0;

    const allKeys = Object.keys(localStorage).filter(k => k.startsWith('journal-'));

    for (const key of allKeys) {
      const dateKey = key.replace('journal-', '');
      const rawText = localStorage.getItem(key) ?? '';

      // Record snapshot in IndexedDB journals table
      await this.db.journals.put({
        dateKey,
        rawMmd: rawText,
        syncedAt: Date.now()
      });

      // Parse lines into preliminary notes if not already imported
      const existingForDate = await this.db.notes.where('zoneId').equals(dateKey).count();
      if (existingForDate === 0 && rawText.trim()) {
        const parsedNotes = this.parseMmdToNotes(rawText, dateKey);
        if (parsedNotes.length > 0) {
          await this.db.notes.bulkPut(parsedNotes);
          totalNotes += parsedNotes.length;
        }
      }

      migratedDates.push(dateKey);
    }

    return { migratedDates, totalNotes };
  }

  /**
   * Serializes current notes back into Mermaid-compatible text and commits
   * to localStorage.setItem(`journal-${dateKey}`, mmd), guaranteeing
   * 100% backward compatibility for Monaco and legacy visualizers.
   */
  async syncGraphToLegacyLocalStorage(dateKey: string, notes: ADHDPostItNote[]): Promise<string> {
    const mmd = this.serializeNotesToMmd(notes);
    localStorage.setItem(`journal-${dateKey}`, mmd);

    // Keep Dexie journals table in sync
    await this.db.journals.put({
      dateKey,
      rawMmd: mmd,
      syncedAt: Date.now()
    });

    return mmd;
  }

  /**
   * Parses plaintext Mermaid diagram / task lists into ADHDPostItNote structures.
   */
  parseMmdToNotes(text: string, dateKey: string): ADHDPostItNote[] {
    const lines = text.split('\n');
    const notes: ADHDPostItNote[] = [];
    const colors: PostItColor[] = ['yellow', 'pink', 'blue', 'green', 'purple', 'orange'];
    let colorIdx = 0;
    let startX = 60;
    let startY = 80;

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trim();
      if (!line || line.startsWith('%%') || line.startsWith('graph ') || line.startsWith('mindmap')) {
        continue;
      }

      // Check for task prefixes (task:, - [ ], etc.) or simple text entries
      let title = line;
      let status: PostItStatus = 'open';

      if (line.includes('[x]') || line.includes('[X]') || line.toLowerCase().includes('done:cross')) {
        status = 'done_cross';
        title = line.replace(/\[x\]|\[X\]|done:cross/gi, '').trim();
      } else if (line.includes('[✓]') || line.toLowerCase().includes('done:check')) {
        status = 'done_check';
        title = line.replace(/\[✓\]|done:check/gi, '').trim();
      } else if (line.startsWith('- [ ]')) {
        title = line.replace('- [ ]', '').trim();
      } else if (line.startsWith('task:')) {
        title = line.replace('task:', '').trim();
      }

      // Clean leading bullet chars
      title = title.replace(/^[-*+]\s*/, '').trim();
      if (!title) continue;

      // Extract hashtags
      const tags = (title.match(/#[\w-]+/g) ?? []).map(t => t.toLowerCase());
      const cleanTitle = title.replace(/#[\w-]+/g, '').trim();

      const note: ADHDPostItNote = {
        id: `note-${dateKey}-${i + 1}`,
        title: cleanTitle || title,
        content: '',
        color: colors[colorIdx % colors.length],
        status,
        tags,
        position: { x: startX, y: startY },
        zIndex: 10 + i,
        zoneId: dateKey,
        createdAt: Date.now(),
        updatedAt: Date.now(),
        cognitiveLoad: 'medium',
        estimatedMinutes: 20,
        isBlocked: false
      };

      notes.push(note);
      colorIdx++;
      startX += 220;
      if (startX > 900) {
        startX = 60;
        startY += 240;
      }
    }

    return notes;
  }

  /**
   * Generates clean Mermaid markdown from a list of notes.
   */
  private serializeNotesToMmd(notes: ADHDPostItNote[]): string {
    const lines: string[] = ['%% Generated by Taskstick Ideation Wall %%'];

    for (const note of notes) {
      const statusMarker = note.status === 'done_cross' ? '[x]' : (note.status === 'done_check' ? '[✓]' : '[ ]');
      const tagStr = note.tags.length ? ' ' + note.tags.join(' ') : '';
      lines.push(`task: ${statusMarker} (${note.color}) ${note.title}${tagStr}`);
    }

    return lines.join('\n');
  }
}
